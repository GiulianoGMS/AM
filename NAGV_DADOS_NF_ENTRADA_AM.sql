CREATE OR REPLACE VIEW NAGV_DADOS_NF_ENTRADA_AM AS
SELECT DTAEMISSAO, NROEMPRESA, CNPJ_EMPRESA_ADQUIRENTE, RAIZ_CNPJ, CANAL_VENDA, CNPJ_FORNECEDOR, NOME_FORNECEDOR, SKU, UF_DESTINO,
       UF_ORIGEM, CNAE_FORNECEDOR, COD_MUNICIPIO_FORNECEDOR, CONTA_CONTABIL, CENTRO_CUSTO, DESCRICAO_PRODUTO_SERVICO,
       COD_SERV_LC116, NCM, EX, CFOP, QTD, UNIDADE, FATOR_CONVERSAO, REGIME_TRIBUTARIO_FORNECEDOR, RAMO_ATIVIDADE_FORNECEDOR,
       TIPO_AQUISICAO, VALOR_OPERACAO, DESCONTO_INCONDICIONAL,
       -- Creditos Fiscais Apropriados (validar se utilizara as colunas da nota, só descomentar)
       0 IPI, 0 PIS_COFINS, 0 ICMS, 0 ICMS_ST,
       -- IPI, PIS_COFINS, ICMS, ICMS_ST,
       ESTORNO_CRED_PIS_COFINS, ESTORNO_CRED_IPI, ESTORNO_CRED_ICMS, ICMS_ST_CALC, ALIQ_IPI_CALC, IPI_CALC,
       ALIQ_PIS_COFINS_CALC, PIS_COFINS_CALC, ALIQ_ICMS_CALC, ICMS_CALC, ALIQ_ISS_CALC, ISS_CALC, INCENTIVO_FISCAL_PIS_COFINS, INCENTIVO_FISCAL_ICMS, ORIGEM,
       ALIQ_LIMITE_ICMS, ALIQ_PISCOFINS_XML, NFECHAVEACESSO

 FROM (

SELECT X.DTAEMISSAO, X.NROEMPRESA, LPAD(DE.NROCGCCPF,12,0) || LPAD(DE.DIGCGCCPF,2,0) CNPJ_EMPRESA_ADQUIRENTE,
       SUBSTR(LPAD(DE.NROCGCCPF,12,0) || LPAD(DE.DIGCGCCPF,2,0), 1, 8) RAIZ_CNPJ,
       NULL CANAL_VENDA,
       LPAD(GE.NROCGCCPF,12,0) || LPAD(GE.DIGCGCCPF,2,0) CNPJ_FORNECEDOR,
       GE.NOMERAZAO NOME_FORNECEDOR,
       XI.SEQPRODUTO SKU,
       DE.UF UF_DESTINO,
       GE.UF UF_ORIGEM,
       GE.CNAE CNAE_FORNECEDOR,
       C.CODIBGE COD_MUNICIPIO_FORNECEDOR,
       NULL CONTA_CONTABIL,
       (SELECT AH.DESCRICAO FROM ABA_HISTORICO AH WHERE AH.SEQHISTORICO = X.CODHISTORICO) CENTRO_CUSTO,
       P.DESCCOMPLETA DESCRICAO_PRODUTO_SERVICO,
       TO_CHAR(COALESCE(TO_NUMBER(EM.ITEMLISTASERVNFSE), X.CODSERVICODEISS, XI.CODSERVICODEISS)) COD_SERV_LC116,
       XI.CODNCM NCM,
       NULL EX,
       XI.CFOP CFOP,
       SUM(XI.QUANTIDADE) QTD,
       XI.UNIDADE UNIDADE,
       NULL FATOR_CONVERSAO,
       R.DESCRICAO REGIME_TRIBUTARIO_FORNECEDOR,
       DECODE(F.TIPFORNECEDOR, 'D','Distribuidor','I','Industria','P','Prestador de Servicos') RAMO_ATIVIDADE_FORNECEDOR,
       NULL TIPO_AQUISICAO,
       SUM(XI.VLRITEM) VALOR_OPERACAO,
       SUM(NVL(XI.VLRDESCONTO,0)) DESCONTO_INCONDICIONAL,
       SUM(NVL(XI.VLRIPI,0)) IPI,
       SUM(NVL(XI.VLRPIS,0) + NVL(XI.VLRCOFINS,0)) PIS_COFINS,
       SUM(NVL(XI.VLRICMS,0)) ICMS,
       SUM(NVL(XI.VLRICMSST,0)) ICMS_ST,
       NULL ESTORNO_CRED_PIS_COFINS,
       NULL ESTORNO_CRED_IPI,
       NULL ESTORNO_CRED_ICMS,
       SUM(NVL(XI.VLRICMSST,0)) ICMS_ST_CALC,
       NVL(XI.ALIQIPI,0) ALIQ_IPI_CALC,
       SUM(NVL(XI.VLRIPI,0)) IPI_CALC,
       NVL(XI.ALIQPIS,0) + NVL(XI.ALIQCOFINS,0) ALIQ_PIS_COFINS_CALC,
       SUM(NVL(XI.VLRPIS,0) + NVL(XI.VLRCOFINS,0)) PIS_COFINS_CALC,
       NVL(XI.ALIQICMS,0) ALIQ_ICMS_CALC,
       SUM(NVL(XI.VLRICMS,0)) ICMS_CALC,
       NVL(XI.ALIQISS,0) ALIQ_ISS_CALC,
       SUM(NVL(XI.VLRISS,0)) ISS_CALC,
       NULL INCENTIVO_FISCAL_PIS_COFINS,
       NULL INCENTIVO_FISCAL_ICMS,
       'ORC' ORIGEM,
       NULL ALIQ_LIMITE_ICMS, NULL ALIQ_PISCOFINS_XML, X.NFECHAVEACESSO

  FROM OR_NFDESPESA X INNER JOIN OR_NFITENSDESPESA XI ON XI.SEQNOTA = X.SEQNOTA
                      INNER JOIN MAX_EMPRESA E ON E.NROEMPRESA = X.NROEMPRESA
                      INNER JOIN MAP_PRODUTO P ON P.SEQPRODUTO = XI.SEQPRODUTO
                      INNER JOIN GE_PESSOA GE ON GE.SEQPESSOA = X.SEQPESSOA
                      INNER JOIN GE_PESSOA DE ON DE.SEQPESSOA = X.NROEMPRESA
                       LEFT JOIN GE_CIDADE C ON C.SEQCIDADE = GE.SEQCIDADE
                      INNER JOIN MAF_FORNECEDOR F ON F.SEQFORNECEDOR = GE.SEQPESSOA
                      INNER JOIN MAF_FORNECDIVISAO D ON D.SEQFORNECEDOR = F.SEQFORNECEDOR
                      INNER JOIN MON_REGIMETRIBUTACAO R ON R.NROREGTRIBUTACAO = D.NROREGTRIBUTACAO
                      INNER JOIN MRL_PRODUTOEMPRESA EM ON EM.SEQPRODUTO = XI.SEQPRODUTO AND EM.NROEMPRESA = 507

 WHERE X.SITUACAO = 'I'

 GROUP BY DE.NROCGCCPF,
          DE.DIGCGCCPF,
          GE.NROCGCCPF,
          GE.DIGCGCCPF,
          GE.NOMERAZAO,
          XI.SEQPRODUTO,
          DE.UF,
          GE.UF,
          P.DESCCOMPLETA,
          XI.CFOP,
          XI.ALIQIPI,
          XI.ALIQICMS,
          XI.CODNCM,
          XI.UNIDADE,
          GE.CNAE,
          C.CODIBGE,
          R.DESCRICAO,
          X.CODHISTORICO,
          COALESCE(TO_NUMBER(EM.ITEMLISTASERVNFSE), X.CODSERVICODEISS, XI.CODSERVICODEISS),
          XI.ALIQISS,
          DECODE(F.TIPFORNECEDOR, 'D','Distribuidor','I','Industria','P','Prestador de Servicos'),
          NVL(XI.ALIQPIS,0) + NVL(XI.ALIQCOFINS,0), X.DTAEMISSAO, X.NROEMPRESA, NFECHAVEACESSO

UNION ALL

SELECT XX.DTAEMISSAO, XX.NROEMPRESA, LPAD(DE.NROCGCCPF,12,0) || LPAD(DE.DIGCGCCPF,2,0) CNPJ_EMPRESA_ADQUIRENTE,
       SUBSTR(LPAD(DE.NROCGCCPF,12,0) || LPAD(DE.DIGCGCCPF,2,0), 1, 8) RAIZ_CNPJ,
       NULL CANAL_VENDA,
       LPAD(GE.NROCGCCPF,12,0) || LPAD(GE.DIGCGCCPF,2,0) CNPJ_FORNECEDOR,
       GE.NOMERAZAO NOME_FORNECEDOR,
       XII.SEQPRODUTO SKU,
       DE.UF UF_DESTINO,
       GE.UF UF_ORIGEM,
       GE.CNAE CNAE_FORNECEDOR,
       C.CODIBGE COD_MUNICIPIO_FORNECEDOR,
       NULL CONTA_CONTABIL,
       NULL CENTRO_CUSTO,
       P.DESCCOMPLETA DESCRICAO_PRODUTO_SERVICO,
       EM.ITEMLISTASERVNFSE COD_SERV_LC116,
       F.CODNBMSH NCM,
       NULL EX,
       XII.CFOP CFOP,
       SUM(XII.QUANTIDADE) QTD,
       FF.EMBALAGEM||'-'||FF.QTDEMBALAGEM UNIDADE,
       FM.FATORCONVEMBXML FATOR_CONVERSAO,
       R.DESCRICAO REGIME_TRIBUTARIO_FORNECEDOR,
       DECODE(FORN.TIPFORNECEDOR, 'D','Distribuidor','I','Industria','P','Prestador de Servicos') RAMO_ATIVIDADE_FORNECEDOR,
       NULL TIPO_AQUISICAO,
       SUM(XII.VLRITEM) VALOR_OPERACAO,
       SUM(NVL(XII.VLRDESCITEM,0)) DESCONTO_INCONDICIONAL,
       NULL IPI,
       SUM(NVL(XII.VLRPIS,0) + NVL(XII.VLRCOFINS,0)) PIS_COFINS,
       SUM(NVL(XII.VLRICMS,0)) ICMS,
       SUM(NVL(XII.VLRICMSST,0)) ICMS_ST,
       NULL ESTORNO_CRED_PIS_COFINS,
       NULL ESTORNO_CRED_IPI,
       NULL ESTORNO_CRED_ICMS,
       SUM(NVL(XII.VLRICMSST,0)) ICMS_ST_NOTA,
       NVL(XII.PERALIQUOTAIPI,0) ALIQ_IPI_NOTA,
       SUM(NVL(XII.VLRIPI,0)) IPI_NOTA,
       NVL(XII.PERALIQUOTAPIS,0) + NVL(XII.PERALIQUOTACOFINS,0) ALIQ_PIS_COFINS_NOTA,
       SUM(NVL(XII.VLRPIS,0) + NVL(XII.VLRCOFINS,0)) PIS_COFINS_NOTA,
       NVL(XII.PERALIQUOTAICMS,0) ALIQ_ICMS_NOTA,
       SUM(NVL(XII.VLRICMS,0)) ICMS_NOTA,
       NVL(XII.PERALIQISS,0) ALIQ_ISS_NOTA,
       SUM(NVL(XII.VLRTOTISS,0)) ISS_NOTA,
       NULL INCENTIVO_FISCAL_PIS_COFINS,
       NULL INCENTIVO_FISCAL_ICMS,
       'REC' ORIGEM,
       CASE WHEN TRIB.PERALIQICMSCALCPRECO = 0 THEN NULL ELSE TRIB.PERALIQICMSCALCPRECO END ALIQ_LIMITE_ICMS,
       NVL(ITEM.M014_VL_PERC_ALIQ_PIS,0) + NVL(ITEM.M014_VL_PERC_ALIQ_CF,0) ALIQ_PISCOFINS_XML, XX.NFECHAVEACESSO

  FROM MLF_NOTAFISCAL XX INNER JOIN MAX_EMPRESA E ON E.NROEMPRESA = XX.NROEMPRESA
                         INNER JOIN MLF_NFITEM XII ON XX.SEQNF = XII.SEQNF
                         INNER JOIN MAP_PRODUTO P ON P.SEQPRODUTO = XII.SEQPRODUTO
                         INNER JOIN GE_PESSOA DE ON DE.SEQPESSOA = XX.NROEMPRESA
                         INNER JOIN GE_PESSOA GE ON GE.SEQPESSOA = XX.SEQPESSOA
                         INNER JOIN MAP_FAMILIA F ON F.SEQFAMILIA = P.SEQFAMILIA
                          LEFT JOIN GE_CIDADE C ON C.SEQCIDADE = GE.SEQCIDADE
                         INNER JOIN MAF_FORNECEDOR FORN ON FORN.SEQFORNECEDOR = GE.SEQPESSOA
                         INNER JOIN MAF_FORNECDIVISAO D ON D.SEQFORNECEDOR = FORN.SEQFORNECEDOR
                          LEFT JOIN MAP_FAMFORNEC FM ON FM.SEQFAMILIA = P.SEQFAMILIA AND FM.SEQFORNECEDOR = D.SEQFORNECEDOR
                         INNER JOIN MAP_FAMEMBALAGEM FF ON FF.SEQFAMILIA = F.SEQFAMILIA AND FF.QTDEMBALAGEM = XII.QTDEMBALAGEM
                         INNER JOIN MON_REGIMETRIBUTACAO R ON R.NROREGTRIBUTACAO = D.NROREGTRIBUTACAO
                         INNER JOIN MRL_PRODUTOEMPRESA EM ON EM.SEQPRODUTO = XII.SEQPRODUTO AND EM.NROEMPRESA = 507
                         INNER JOIN MAP_TRIBUTACAOUF TRIB ON TRIB.NROTRIBUTACAO = XII.CODTRIBUTACAO AND TRIB.NROREGTRIBUTACAO = D.NROREGTRIBUTACAO 
                                    AND TRIB.TIPTRIBUTACAO = DECODE(FORN.TIPFORNECEDOR, 'I', 'EI','D','ED', 'EI') AND TRIB.UFEMPRESA = DE.UF AND TRIB.UFCLIENTEFORNEC = GE.UF
                         INNER JOIN TMP_M000_NF CAPA ON CAPA.M000_NR_CHAVE_ACESSO = XX.NFECHAVEACESSO
                         INNER JOIN TMP_M014_ITEM ITEM ON ITEM.M000_ID_NF = CAPA.M000_ID_NF AND ITEM.M014_NR_ITEM = XII.SEQORDEMNFE

 WHERE XX.STATUSNF = 'V'
   AND XII.VLRITEM > 0
   AND XII.QUANTIDADE > 0
   AND XX.TIPNOTAFISCAL = 'E'
   -- Filtra cgc diferente
   AND SUBSTR(LPAD(DE.NROCGCCPF,12,0) || LPAD(DE.DIGCGCCPF,2,0), 1, 8) != SUBSTR(LPAD(GE.NROCGCCPF,12,0) || LPAD(GE.DIGCGCCPF,2,0), 1, 8)

 GROUP BY DE.NROCGCCPF,
          DE.DIGCGCCPF,
          GE.NROCGCCPF,
          GE.DIGCGCCPF,
          GE.NOMERAZAO,
          XII.SEQPRODUTO,
          DE.UF,
          GE.UF,
          GE.CNAE,
          C.CODIBGE,
          P.DESCCOMPLETA,
          F.CODNBMSH,
          XII.CFOP,
          FF.EMBALAGEM||'-'||FF.QTDEMBALAGEM,
          R.DESCRICAO,
          DECODE(FORN.TIPFORNECEDOR, 'D','Distribuidor','I','Industria','P','Prestador de Servicos'),
          NVL(XII.PERALIQUOTAPIS,0) + NVL(XII.PERALIQUOTACOFINS,0), XII.PERALIQISS, XII.PERALIQUOTAIPI,
          XII.PERALIQUOTAICMS, XX.DTAEMISSAO, EM.ITEMLISTASERVNFSE, FM.FATORCONVEMBXML, XX.NROEMPRESA,
          CASE WHEN TRIB.PERALIQICMSCALCPRECO = 0 THEN NULL ELSE TRIB.PERALIQICMSCALCPRECO END, NVL(ITEM.M014_VL_PERC_ALIQ_PIS,0) + NVL(ITEM.M014_VL_PERC_ALIQ_CF,0), NFECHAVEACESSO

) BASE
;
