CREATE OR REPLACE VIEW NAGV_DADOS_NF_SAIDA_AM AS
SELECT /*+OPTIMIZER_FEATURES_ENABLE('11.2.0.4')*/
       XX.DTAMOVIMENTO,
       LPAD(G.NROCGCCPF,12,0)||LPAD(G.DIGCGCCPF,2,0) CNPJ_EMPRESA,
       SUBSTR(LPAD(G.NROCGCCPF,12,0) || LPAD(G.DIGCGCCPF,2,0), 1, 8) RAIZ_CNPJ,
       S.SEGMENTO CANAL_VENDA,
       F.CODNBMSH NCM,
       XI.SEQPRODUTO SKU,
       CASE WHEN XX.SEQPESSOA = XX.NROEMPRESA THEN NULL ELSE LPAD(D.NROCGCCPF,12,0) || LPAD(D.DIGCGCCPF,2,0) END CNPJ_TOMADOR,
       G.UF UF_ORIGEM,
       D.UF UF_DESTINO,
       C.DESCRICAO TIPO_OPERACAO,
       NULL TIPO_MOVIMENTACAO,
       P.DESCCOMPLETA DESCRICAO_PRODUTO_SERVICO,
       XI.CFOP CFOP,
       XI.CODORIGEMTRIB||XI.SITUACAONF CST,
       SUM(NVL(XI.QUANTIDADE,0)) QTD,
       XI.QTDEMBALAGEM UNIDADE,
       NULL FATOR_CONVERSAO,
       SUM(NVL(XI.VLRITEM,0)) VALOR_OPERACAO,
       SUM(NVL(XI.VLRDESCONTO,0)) DESCONTO_INCONDICIONAL,
       NULL DESCONTO_CONDICIONAL,
       SUM(NVL(XI.VLRIPI,0)) IPI,
       SUM(NVL(XI.VLRPIS,0) + NVL(XI.VLRCOFINS,0)) PIS_COFINS,
       SUM(NVL(XI.VLRICMS,0)) ICMS,
       SUM(NVL(XI.VLRICMSST,0)) ICMS_ST,
       SUM(NVL(XI.VLRTOTISS,0)) ISS,
       NULL INCENTIVO_FISCAL_PIS_COFINS,
       NULL INCENTIVO_FISCAL_ICMS,
       '0' COGS_TOTAL,
       '0' COGS_CUSTOS_SERVICOS_PRESTADOS,
       '0' COGS_FOPAG,
       '0' SGA_TOTAL,
       '0' SGA_FOPAG,
       '0' SGA_DESPESAS_OPERACIONAIS,
       XX.NFECHAVEACESSO,
       XX.NROEMPRESA

  FROM MFL_DOCTOFISCAL XX INNER JOIN MAX_EMPRESA E ON E.NROEMPRESA = XX.NROEMPRESA
                          INNER JOIN MFL_DFITEM XI ON XX.SEQNF = XI.SEQNF
                          INNER JOIN MAP_PRODUTO P ON P.SEQPRODUTO = XI.SEQPRODUTO
                          INNER JOIN GE_PESSOA G   ON G.SEQPESSOA = XX.NROEMPRESA
                          INNER JOIN MAP_FAMILIA F ON F.SEQFAMILIA = P.SEQFAMILIA
                          INNER JOIN MON_SEGMENTO S ON S.NROSEGMENTO = XX.NROSEGMENTO
                          INNER JOIN GE_PESSOA D ON D.SEQPESSOA = XX.SEQPESSOA
                          INNER JOIN MAX_CODGERALOPER C ON C.CODGERALOPER = XX.CODGERALOPER
 WHERE 1=1
   AND XX.STATUSDF = 'V'
   AND XI.STATUSITEM = 'V'
   AND XI.VLRITEM > 0
   AND XI.QUANTIDADE > 0
   --AND SUBSTR(LPAD(G.NROCGCCPF,12,0) || LPAD(G.DIGCGCCPF,2,0), 1, 8) != SUBSTR(LPAD(D.NROCGCCPF,12,0) || LPAD(D.DIGCGCCPF,2,0), 1, 8)
   
 GROUP BY XX.DTAMOVIMENTO,
          G.NROCGCCPF,
          G.DIGCGCCPF,
          S.SEGMENTO,
          F.CODNBMSH,
          XI.SEQPRODUTO,
          CASE WHEN XX.SEQPESSOA = XX.NROEMPRESA THEN NULL ELSE LPAD(D.NROCGCCPF,12,0) || LPAD(D.DIGCGCCPF,2,0) END,
          G.UF,
          D.UF,
          C.DESCRICAO,
          P.DESCCOMPLETA,
          XI.CFOP,
          XI.CODORIGEMTRIB||XI.SITUACAONF,
          XI.QTDEMBALAGEM,
          XX.NFECHAVEACESSO,
          XX.NROEMPRESA

UNION

SELECT /*+OPTIMIZER_FEATURES_ENABLE('11.2.0.4')*/
       XX.DTAEMISSAO PERIODO,
       LPAD(G.NROCGCCPF,12,0)||LPAD(G.DIGCGCCPF,2,0) CNPJ_EMPRESA,
       SUBSTR(LPAD(G.NROCGCCPF,12,0) || LPAD(G.DIGCGCCPF,2,0), 1, 8) RAIZ_CNPJ,
       S.SEGMENTO CANAL_VENDA,
       F.CODNBMSH NCM,
       XI.SEQPRODUTO SKU,
       CASE WHEN XX.SEQPESSOA = XX.NROEMPRESA THEN NULL ELSE LPAD(D.NROCGCCPF,12,0) || LPAD(D.DIGCGCCPF,2,0) END CNPJ_TOMADOR,
       G.UF UF_ORIGEM,
       D.UF UF_DESTINO,
       X.DESCRICAO TIPO_OPERACAO,
       NULL TIPO_MOVIMENTACAO,
       P.DESCCOMPLETA DESCRICAO_PRODUTO_SERVICO,
       XI.CFOP CFOP,
       XI.CODORIGEMTRIB||XI.SITUACAONF CST,
       SUM(NVL(XI.QUANTIDADE,0)) QTD,
       XI.QTDEMBALAGEM UNIDADE,
       NULL FATOR_CONVERSAO,
       SUM(NVL(XI.VLRITEM,0)) VALOR_OPERACAO,
       SUM(NVL(XI.VLRDESCITEM,0)) DESCONTO_INCONDICIONAL,
       NULL DESCONTO_CONDICIONAL,
       SUM(NVL(XI.VLRIPI,0)) IPI,
       SUM(NVL(XI.VLRPIS,0) + NVL(XI.VLRCOFINS,0)) PIS_COFINS,
       SUM(NVL(XI.VLRICMS,0)) ICMS,
       SUM(NVL(XI.VLRICMSST,0)) ICMS_ST,
       SUM(NVL(XI.VLRTOTISS,0)) ISS,
       NULL INCENTIVO_FISCAL_PIS_COFINS,
       NULL INCENTIVO_FISCAL_ICMS,
       '0' COGS_TOTAL,
       '0' COGS_CUSTOS_SERVICOS_PRESTADOS,
       '0' COGS_FOPAG,
       '0' SGA_TOTAL,
       '0' SGA_FOPAG,
       '0' SGA_DESPESAS_OPERACIONAIS,
       XX.NFECHAVEACESSO,
       XX.NROEMPRESA

  FROM MLF_NOTAFISCAL XX INNER JOIN MAX_EMPRESA E ON E.NROEMPRESA = XX.NROEMPRESA
                         INNER JOIN MLF_NFITEM XI ON XX.SEQNF = XI.SEQNF
                         INNER JOIN MAP_PRODUTO P ON P.SEQPRODUTO = XI.SEQPRODUTO
                         INNER JOIN GE_PESSOA G   ON G.SEQPESSOA = XX.NROEMPRESA
                         INNER JOIN MAP_FAMILIA F ON F.SEQFAMILIA = P.SEQFAMILIA
                         INNER JOIN MAX_CODGERALOPER X ON X.CODGERALOPER = XX.CODGERALOPER
                         INNER JOIN GE_PESSOA D ON D.SEQPESSOA = XX.SEQPESSOA
                         INNER JOIN MON_SEGMENTO S ON S.NROSEGMENTO = XX.NROSEGMENTO
 WHERE 1=1
   AND XX.STATUSNF = 'V'
   AND XX.STATUSNFE = '4'
   AND XI.VLRITEM > 0
   AND XI.QUANTIDADE > 0
   -- AND XX.CODGERALOPER NOT IN (37,48,123,610,615,613,810,916,910,911,76)
   /* AND XX.CODGERALOPER NOT IN (SELECT CODGERALOPER FROM MAX_CODGERALOPER T WHERE TIPCGO = 'S' AND TIPUSO = 'E' AND TIPDOCFISCAL = 'O') */
   AND XX.SERIENF != 'CF'
   AND (XX.TIPNOTAFISCAL = 'S' OR X.DESCRICAO LIKE '%EMI%' AND X.TIPCGO = 'E')
   AND XX.MODELONF IN (55,65)
   
 GROUP BY XX.DTAEMISSAO,
          G.NROCGCCPF,
          G.DIGCGCCPF,
          S.SEGMENTO,
          F.CODNBMSH,
          XI.SEQPRODUTO,
          CASE WHEN XX.SEQPESSOA = XX.NROEMPRESA THEN NULL ELSE LPAD(D.NROCGCCPF,12,0) || LPAD(D.DIGCGCCPF,2,0) END,
          G.UF,
          D.UF,
          X.DESCRICAO,
          P.DESCCOMPLETA,
          XI.CFOP,
          XI.CODORIGEMTRIB||XI.SITUACAONF,
          XI.QTDEMBALAGEM,
          XX.NFECHAVEACESSO,
          XX.NROEMPRESA;
